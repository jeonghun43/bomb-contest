"""
render.py - Turn a Bomb into a self-contained source directory.

    OUT/
      bomb.c                 student copy of main (CMU or drill)
      phases.c               #includes the chosen phase templates in order
      bombdata.h             per-seed macros, nothing else
      support.[ch] phases.h driverlib.[ch]   shared runtime
      cmu/..., drills/...    the phase templates used
      Makefile.bomb          the one set of compiler flags
      answers.txt            one answer per phase
      answers_secret.txt     with the secret token and the secret answer
      SOLUTION.md            operator write-up: answers, walkthroughs, hints
      notes/stageN.md        student write-up, released after defusal
      hints/stageN-K.md      student hints, released over time
      manifest.json          kind, seed, variants, expected canaries

Only bomb and bomb.c ever reach a student. Output is a pure function of the
Bomb, so the same (kind, seed) always renders the same bytes.
"""

import hashlib
import json
import os
import shutil
import time

from .core import Raw

CSRC =os.path.join(os.path.dirname(os.path.abspath(__file__)), "csrc")
COMMON = ["support.c", "support.h", "phases.h", "driverlib.c", "driverlib.h"]
TOOLCHAIN = "gcc (Ubuntu 4.8.1-2ubuntu1~12.04) 4.8.1"


class RenderError(Exception):
    pass


# --------------------------------------------------------------------------
# C literals
# --------------------------------------------------------------------------

def _escape(ch, quote):
    """One character inside a C literal delimited by `quote`."""
    if ch == quote or ch == "\\":
        return "\\" + ch
    if 0x20 <= ord(ch) < 0x7F:
        return ch
    return "\\%03o" % (ord(ch) & 0xFF)


def c_string(s):
    return '"' + "".join(_escape(ch, '"') for ch in s) + '"'


def c_char(ch):
    return "'" + _escape(ch, "'") + "'"


def c_value(v):
    if isinstance(v, Raw):
        return v.text
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return c_string(v)
    if isinstance(v, (list, tuple)):
        items = []
        for x in v:
            if isinstance(x, str) and len(x) == 1:
                items.append(c_char(x))
            else:
                items.append(c_value(x))
        return "{" + ", ".join(items) + "}"
    raise RenderError("cannot render %r as C" % (v,))


