def bombdata_h(bomb):
    out = ["/* bombdata.h - generated by bank/render.py for %s seed %d.",
           " * Do not edit. Do not distribute: these are the answers. */",
           "#ifndef BOMBDATA_H", "#define BOMBDATA_H", "",
           "#define NUM_PHASES  %d" % bomb.num_phases,
           "#define HAS_SECRET  %d" % (1 if bomb.has_secret else 0)]
    out[0] %= (bomb.kind, bomb.seed)
    if bomb.has_secret:
        out.append("#define SECRET_LINE %d" % bomb.secret_line)
        out.append("#define SECRET_WORD %s" % c_string(bomb.secret_word))
    for i, p in enumerate(bomb.phases):
        label = "secret phase" if p.slot == "secret" else "phase %d" % (i + 1)
        out += ["", "/* %s: %s (%s) */" % (label, p.slot, p.variant)]
        for name, value in p.macros:
            out.append("#define %s %s" % (name, c_value(value)))
    out += ["", "#endif", ""]
    return "\n".join(out)


def phases_c(bomb):
    out = ["/* phases.c - generated by bank/render.py. Every phase lives in this",
           " * one translation unit, as in the original bomb, so symbol order,",
           " * static-local names and data layout come out the same. */",
           "#include <stdio.h>", "#include <stdlib.h>",
           '#include "bombdata.h"', '#include "support.h"', '#include "phases.h"',
           ""]
    out += ['#include "%s"' % p.template for p in bomb.phases]
    return "\n".join(out) + "\n"


def _safe_title(s):
    for bad in ('"', "\\", "%", "*/", "\n"):
        if bad in s:
            raise RenderError("drill title may not contain %r" % bad)
    return s


def main_c(bomb):
    with open(os.path.join(CSRC, "common", bomb.main)) as f:
        src = f.read()
    if bomb.main == "drill_main.c":
        src = src.replace("@DRILL_ID@", _safe_title(bomb.drill_id))
        src = src.replace("@DRILL_TITLE@", _safe_title(bomb.drill_title))
    return src


