def rmtree(path):
    """
    shutil.rmtree that rides out transient EACCES. On a Windows drive under
    WSL (/mnt/c) a virus scanner or the indexer can hold a file we just wrote
    for a moment.
    """
    for attempt in range(20):
        try:
            shutil.rmtree(path)
            return
        except FileNotFoundError:
            return
        except PermissionError:
            if attempt == 19:
                raise
            time.sleep(0.25)


def _prepare(out):
    if os.path.exists(out):
        if os.listdir(out) and not os.path.isfile(
                os.path.join(out, "manifest.json")):
            raise RenderError("%s exists and is not a rendered bomb; "
                              "refusing to overwrite" % out)
        rmtree(out)
    os.makedirs(out)


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def digest(out, skip=("bomb", ".fuzz_in")):
    """{relative path: sha256} of every rendered file (not build outputs)."""
    sums = {}
    for dirpath, _, files in os.walk(out):
        for name in files:
            if name in skip or name.endswith(".o"):
                continue
            path = os.path.join(dirpath, name)
            with open(path, "rb") as f:
                sums[os.path.relpath(path, out)] = \
                    hashlib.sha256(f.read()).hexdigest()
    return sums


def write(bomb, out):
    """Render bomb into directory out (replacing an earlier render)."""
    _prepare(out)
    for name in COMMON:
        shutil.copyfile(os.path.join(CSRC, "common", name),
                        os.path.join(out, name))
    shutil.copyfile(os.path.join(CSRC, "Makefile.bomb"),
                    os.path.join(out, "Makefile.bomb"))
    for p in bomb.phases:
        dst = os.path.join(out, p.template)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(CSRC, p.template), dst)

    _write(os.path.join(out, "bomb.c"), main_c(bomb))
    _write(os.path.join(out, "phases.c"), phases_c(bomb))
    _write(os.path.join(out, "bombdata.h"), bombdata_h(bomb))
    _write(os.path.join(out, "answers.txt"),
           "\n".join(bomb.answer_lines()) + "\n")
    if bomb.has_secret:
        _write(os.path.join(out, "answers_secret.txt"),
               "\n".join(bomb.answer_lines(with_secret=True)) + "\n")
    _write(os.path.join(out, "SOLUTION.md"), solution_md(bomb))
    for i in range(len(bomb.phases)):
        _write(os.path.join(out, "notes", "stage%d.md" % (i + 1)),
               note_md(bomb, i))
        for k in range(3):
            _write(os.path.join(out, "hints", "stage%d-%d.md" % (i + 1, k + 1)),
                   hint_md(bomb, i, k))
    _write(os.path.join(out, "manifest.json"),
           json.dumps(manifest(bomb), indent=2, ensure_ascii=False) + "\n")
