# write-ups
# --------------------------------------------------------------------------

def _label(bomb, i):
    p = bomb.phases[i]
    return "Secret phase" if p.slot == "secret" else "Phase %d" % (i + 1)


def solution_md(bomb):
    v = bomb.variants()
    out = ["# SOLUTION — %s, seed %d" % (bomb.kind, bomb.seed), "",
           "**운영자 전용. 학생에게 배포 금지.**", "",
           "- 종류: %s%s" % (bomb.title,
                           " (%s: %s)" % (bomb.drill_id, bomb.drill_title)
                           if bomb.drill_id else ""),
           "- 변형 계열: " + ", ".join("%s=%s" % (k, v[k]) for k in v),
           "", "## 정답 한 벌", "", "```"]
    out += bomb.answer_lines(with_secret=bomb.has_secret)
    out += ["```", ""]
    if bomb.has_secret:
        out += ["숨은 단계 진입: %d번째 줄 끝에 `%s`를 덧붙인다." %
                (bomb.secret_line + 1, bomb.secret_word), ""]
    for i, p in enumerate(bomb.phases):
        out += ["---", "", "## %s — %s (`%s`)" % (_label(bomb, i), p.title,
                                                 p.variant), "",
                "**정답**: " + p.answers, "", p.walkthrough.rstrip(), "",
                "**힌트**", ""]
        out += ["%d. %s" % (k + 1, h) for k, h in enumerate(p.hints)]
        out.append("")
    return "\n".join(out)


NOTE_CAVEAT = ("> 해설의 어셈블리는 대표적인 모양이다. 실제 주소·레지스터·명령어 "
               "순서는 폭탄마다 조금씩 다를 수 있으니 `objdump -d`로 직접 확인하라.")


def note_md(bomb, i):
    p = bomb.phases[i]
    return "# %s — %s\n\n%s\n\n%s\n\n**이 폭탄의 정답**: %s\n" % (
        _label(bomb, i), p.title, NOTE_CAVEAT, p.walkthrough.rstrip(),
        p.answers)


def hint_md(bomb, i, k):
    p = bomb.phases[i]
    return "# %s 힌트 %d/3\n\n%s\n" % (_label(bomb, i), k + 1, p.hints[k])


def manifest(bomb):
    return {
        "kind": bomb.kind,
        "seed": bomb.seed,
        "title": bomb.title,
        "drill_id": bomb.drill_id,
        "drill_title": bomb.drill_title,
        "num_phases": bomb.num_phases,
        "has_secret": bomb.has_secret,
        "variants": bomb.variants(),
        "canary": bomb.canary_set(),
        "toolchain": TOOLCHAIN,
        "phases": [{"number": i + 1, "slot": p.slot, "variant": p.variant,
                    "title": p.title} for i, p in enumerate(bomb.phases)],
    }


